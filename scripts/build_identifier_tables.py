r"""Write `src/scenet/identifier_tables.py`, the characters an identifier is made of.

An actor id or a panel name is letters, digits, combining marks, `_` and `-`. Python's
`re` has no `\p{L}`, and ECMAScript's names the letters of whichever Unicode its engine
ships, so an editor and `scenet check` would disagree about a letter one knows and the
other does not. So the classes are spelled out, code point by code point, from one Unicode
version, pinned here, and committed: every Python and every editor reads the same table.

The table is generated from Python's own `unicodedata`, so it is written by a Python whose
Unicode is the pinned one. `--check` exits 1 when the committed table is stale; a Python
with another Unicode can only say so.

Usage:
    uv run python scripts/build_identifier_tables.py [--check]
"""

import argparse
import sys
import unicodedata
from collections.abc import Callable, Iterable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "src" / "scenet" / "identifier_tables.py"

#: The Unicode version the table is read from: Python 3.14's.
UNICODE_VERSION = "16.0.0"

#: General categories, by what an identifier makes of them.
LETTER = ("Lu", "Ll", "Lt", "Lm", "Lo")
MARK = ("Mn", "Mc")
DIGIT = ("Nd",)

#: The punctuation an identifier may hold beside its letters, digits and marks.
JOINERS = "_-"

#: The characters a reserved word is spelled with, each matched as `str.casefold` would.
CASED = "abcdefghijklmnopqrstuvwxyzé_"


def _ranges(points: Iterable[int]) -> list[tuple[int, int]]:
    """Consecutive code points as `(first, last)` ranges, in order."""
    found: list[tuple[int, int]] = []
    for point in sorted(points):
        if found and found[-1][1] == point - 1:
            found[-1] = (found[-1][0], point)
        else:
            found.append((point, point))
    return found


def _escaped(point: int) -> str:
    r"""A code point as Python source for a regular expression both dialects read alike.

    Below U+10000 it is the escape `\uXXXX`, which Python's `re` and ECMAScript's read the
    same; above, the character itself, since ECMAScript's `\u{...}` is not Python's, nor
    Python's `\U...` ECMAScript's. Here, as Python source in a string that is not raw: the
    backslash doubled, or the character escaped for this file only.
    """
    if point < 0x10000:  # the end of the Basic Multilingual Plane
        return f"\\\\u{point:04x}"
    return f"\\U{point:08x}"


def _class(points: Iterable[int]) -> str:
    """The inside of a character class naming exactly `points`, as Python source."""
    return "".join(
        _escaped(first) if first == last else f"{_escaped(first)}-{_escaped(last)}"
        for first, last in _ranges(points)
    )


def _where(test: Callable[[str], bool]) -> list[int]:
    return [point for point in range(sys.maxunicode + 1) if test(chr(point))]


def _wrapped(name: str, body: str, width: int = 88) -> str:
    """`name = (...)`, the string cut into lines of at most `width`, never inside an escape."""
    pieces: list[str] = []
    index = 0
    while index < len(body):
        if body.startswith("\\\\u", index):
            size = 7
        elif body.startswith("\\U", index):
            size = 10
        else:
            size = 1
        pieces.append(body[index : index + size])
        index += size
    lines: list[str] = []
    line = ""
    for piece in pieces:
        if len(line) + len(piece) > width - 6:
            lines.append(line)
            line = ""
        line += piece
    if line:
        lines.append(line)
    quoted = "\n".join(f'    "{part}"' for part in lines)
    return f"{name} = (\n{quoted}\n)\n"


def render() -> str:
    """The module, as it is committed."""
    category = unicodedata.category
    starts = _where(lambda char: category(char) in (*LETTER, *DIGIT))
    continues = _where(lambda char: category(char) in (*LETTER, *MARK, *DIGIT) or char in JOINERS)
    cases = {
        cased: _where(lambda char, cased=cased: char.casefold() == cased.casefold())
        for cased in CASED
    }
    case_lines = "\n".join(f'    "{cased}": "{_class(points)}",' for cased, points in cases.items())
    return (
        'r"""The characters an identifier is made of, from Unicode '
        f"{UNICODE_VERSION}.\n\n"
        "Generated by `scripts/build_identifier_tables.py`; do not edit. Each string is the\n"
        "inside of a regular expression's character class, in the escapes Python's `re` and\n"
        "ECMAScript's (with the `u` flag) read alike: `\\uXXXX` below U+10000, the character\n"
        "itself above. :mod:`scenet.identifiers` builds the grammar from them.\n"
        '"""\n\n'
        f'UNICODE_VERSION = "{UNICODE_VERSION}"\n\n'
        "#: What an identifier starts with: a letter (general categories Lu, Ll, Lt, Lm and\n"
        "#: Lo) or a decimal digit (Nd).\n"
        + _wrapped("STARTS", _class(starts))
        + "\n#: What follows: a letter, a decimal digit, a combining mark (Mn and Mc, which spell\n"
        "#: many a letter -- `é` decomposed, every vowel sign of Devanagari), `_` or `-`.\n"
        + _wrapped("CONTINUES", _class(continues))
        + "\n"
        "#: Each character a reserved word is spelled with, and every character whose\n"
        "#: `str.casefold` is it: `k` is also the Kelvin sign, `s` also the long s.\n"
        f"CASES = {{\n{case_lines}\n}}\n"
    )


def main(argv: list[str] | None = None) -> int:
    """Write the table, or with `--check`, exit 1 when the committed one is stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if the table is stale")
    args = parser.parse_args(argv)
    if unicodedata.unidata_version != UNICODE_VERSION:
        print(
            f"this Python has Unicode {unicodedata.unidata_version}; the table is read from "
            f"{UNICODE_VERSION}, so run this with the Python that has it",
            file=sys.stderr,
        )
        return 2
    written = render()
    if args.check:
        stale = TARGET.read_text(encoding="utf-8") != written
        if stale:
            print(f"{TARGET.relative_to(ROOT)} is stale; run {Path(__file__).name}")
        return 1 if stale else 0
    TARGET.write_bytes(written.encode("utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
